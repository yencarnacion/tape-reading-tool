import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../internal/server/web/daily-extension.js', import.meta.url), 'utf8');
const { dailyExtension, dailyExtensionLabels } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const history = Array.from({length:19}, (_,i) => ({sessionDateET:`2026-09-${String(i+1).padStart(2,'0')}`,close:i===18?102:i===17?101:100}));
const value = dailyExtension(history,'2026-10-09',120);
assert.equal(value.days,3); assert.equal(value.direction,1); assert.equal(value.atLeast,false);
assert.ok(Math.abs(value.upper-109.85114934936759)<1e-10);
assert.ok(Math.abs(value.extension-9.238729599774409)<1e-10);
assert.equal(dailyExtensionLabels(value).run,'↑3D*');
assert.equal(dailyExtensionLabels(value).band,'↑9.2%');
const down = dailyExtension(history.map(b=>({...b,close:200-b.close})),'2026-10-09',80);
assert.equal(down.days,3); assert.equal(down.direction,-1); assert.ok(down.extension<0);
assert.equal(dailyExtension(history,'2026-10-09',102).days,0,'equal close breaks the run');
assert.equal(dailyExtension(history,'2026-10-09',101).days,1,'opposite price starts a new run');
assert.equal(dailyExtension(history.slice(-2),'2026-10-09',120).bbReady,false);
assert.equal(dailyExtensionLabels(dailyExtension([],'2026-10-09',120)).band,'—');
assert.equal(dailyExtension(history,'2026-10-09',NaN).streakReady,false);
const polluted = [...history,history.at(-1),{sessionDateET:'2026-10-09',close:999},{sessionDateET:'2026-10-12',close:1}].reverse();
assert.deepEqual(dailyExtension(polluted,'2026-10-09',120),value,'sort, duplicates, current/future daily bars');
history.at(-1).close=NaN;
assert.equal(dailyExtension(history,'2026-10-09',120).streakReady,false);
console.log('Daily extension: BB(20,2), signed band distance, streaks, missing data and replay boundary passed.');
