import assert from 'node:assert/strict';
import {createOptionsView} from '../internal/server/web/options-volatility-panel.js';
function node(){const map=new Map();return {textContent:'',title:'',dataset:{},querySelector(k){if(!map.has(k))map.set(k,node());return map.get(k);},replaceChildren(){},append(){}};}
globalThis.document={createElement:()=>node()};
let mono=1000;Object.defineProperty(performance,'now',{value:()=>mono});
const at=Date.parse('2026-07-24T13:30:20Z');
let snapshot={symbol:'TEST',generation:1,mode:'replay',clockUS:at*1000,status:{connected:true},trades:[]};
const root=node(),requests=[],abort=new AbortController();
const view=createOptionsView({root,host:{signal:abort.signal,isCurrent:()=>true,getOptionsSnapshot:args=>new Promise(resolve=>requests.push({...args,resolve}))},getSnapshot:()=>snapshot,getADRExtension:()=>0});
const render=()=>{mono+=1000;view.render(snapshot.clockUS);};
const settle=()=>new Promise(resolve=>setImmediate(resolve));
const wide=(stamp,generation=1)=>({schemaVersion:1,symbol:'TEST',generation,replay:true,estimated:true,status:'poor-quality',asOfMS:stamp,contracts:[],quality:{ivBid:.5,ivAsk:.9,maxSpread:.5,contracts:6},method:'test estimate'});
view.event({type:'snapshot'});render();
assert.equal(requests[0].afterMS,0);
requests[0].resolve({...wide(at),samples:[wide(at-5000),wide(at)]});await settle();render();
assert.equal(root.querySelector('.vol-state').textContent,'OPTIONS WIDE');
assert.equal(root.querySelector('.vol-quality').textContent,'REPLAY · EST.');
assert.equal(root.querySelector('.vol-iv').textContent,'50–90%');
assert.equal(root.querySelector('.vol-change').textContent,'bid–ask IV estimate');
assert.equal(root.querySelector('.vol-peak').textContent,'--');
assert.equal(requests[1].afterMS,at,'pause requests only samples after the frozen cursor');
requests[1].resolve(wide(at));await settle();render();
assert.equal(root.querySelector('.vol-iv').textContent,'50–90%','paused value is stable');
snapshot={...snapshot,generation:2,clockUS:(at-10000)*1000};view.event({type:'snapshot'});render();
const back=requests.at(-1);assert.equal(back.afterMS,0,'backward seek rebuilds from prepared start');
back.resolve({...wide(at,2),samples:[wide(at,2)]});await settle();render();
assert.equal(root.querySelector('.vol-iv').textContent,'--','a future sample cannot survive a backward seek');
requests.at(-1).resolve({...wide(at-10000,2),replay:false});await settle();render();
assert.equal(root.querySelector('.vol-iv').textContent,'--','replay refuses current live snapshot payloads');
view.unmount();
console.log('Historical options UI: range labeling, pause cursor, backward reset, future/live isolation passed');
